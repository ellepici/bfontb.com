    /// <summary>Chiave (per ordinare) e nome del blocco di un punto di codice.</summary>
    public static (int Key, string Name) Of(int cp)
    {
        int lo = 0, hi = Blocks.Length - 1;
        while (lo <= hi)
        {
            int mid = (lo + hi) / 2;
            var b = Blocks[mid];
            if (cp < b.Start) hi = mid - 1;
            else if (cp > b.End) lo = mid + 1;
            else return (b.Start, b.Name);
        }
        int start = cp & ~0x7F;   // blocco non in elenco: raggruppiamo per 128 punti di codice
        return (start, $"Other characters U+{start:X4}–U+{start + 0x7F:X4}");
    }
